export function attachToolMeta<T extends { name: string }>(
  tool: T,
): T & { meta: QboToolMeta } {
  const meta = TOOL_META[tool.name];
  if (!meta) {
    throw new Error(`QuickBooks tool "${tool.name}" has no operation metadata`);
  }

  return { ...tool, meta };
}
